"""Recompute needs_human from what is actually stored, with explicit reasons. Answers are never changed.

  python -m agent.reflag --pass 2
Flag reasons: no_verified_evidence | auth_unknown | self_serve_unclear | contradiction | no_mcp_evidence_but_claimed
(Schema violations are counted in stats but are no longer a human flag: they were flagging 74 records and drowned real doubt.)
"""
import argparse, json
from collections import Counter
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def reasons(r):
    out = []
    ev = [e for e in r["evidence"] if e["quote_verified"]]
    if not ev: out.append("no_verified_evidence")
    if not r["auth_methods"]: out.append("auth_unknown")
    if r["self_serve"] == "unclear": out.append("self_serve_unclear")
    if any(x.startswith("contradiction") for x in r["verification_log"]): out.append("contradiction")
    m = r["existing_mcp"]
    if m["exists"] and not any("mcp" in (e["url"] + e["field_supported"]).lower() for e in ev): out.append("mcp_claimed_without_verified_evidence")
    return out

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--pass", dest="p", default="2"); a = ap.parse_args()
    d = ROOT / "results" / f"pass{a.p}"; c = Counter(); flagged = []
    for f in sorted(d.glob("*.json")):
        r = json.loads(f.read_text(encoding="utf-8")); rs = reasons(r)
        r["needs_human"] = {"flag": bool(rs), "reason": ", ".join(rs)}
        f.write_text(json.dumps(r, indent=2, ensure_ascii=False), encoding="utf-8")
        c.update(rs)
        if rs: flagged.append((r["id"], r["app"], rs))
    lines = ["# Human interventions", "", f"Generated by `agent/reflag.py` from pass {a.p}. {len(flagged)} of 100 records need a human.", "",
             "## Why a human was needed (counts)", ""] + [f"- `{k}`: {v}" for k, v in c.most_common()] + \
            ["", "## Also done by hand", "- Composio CLI install and `composio login` (browser approval).",
             "- Creating the public GitHub repo and pushing (the environment token could not).",
             "- Hand-checking the 28-app sample (`verification/sample.csv`).",
             "- Turning on GitHub Pages.", "", "## Flagged records", ""] + [f"- {i} {n}: {', '.join(rs)}" for i, n, rs in flagged]
    (ROOT / "HUMAN_INTERVENTIONS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(flagged)} flagged;", dict(c))
main() if __name__ == "__main__" else None
